"""PyTorch Dataset for battery SOH estimation.

Supports three data sources (auto-detected):
  1. NASA PCoE  — .mat files in data/nasa_pcoe/
  2. CALCE       — CSV files in data/calce/
  3. Synthetic   — generated by battery_sim (自动降级兜底)

数据合并优先级: NASA > CALCE > Synthetic
"""
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, random_split
from pathlib import Path
from sklearn.preprocessing import StandardScaler
import pickle


# ============================================================
# Dataset
# ============================================================

class BatteryDataset(Dataset):
    """Dataset yielding (features, soh_target, dv_measured, cell_id, cycle).

    Feature vector (132-d):
        [IC_curve (128), temperature, log_cycle_norm, dv_start, capacity_meas]
    """

    def __init__(
        self,
        features: np.ndarray,    # (N, 132)
        soh: np.ndarray,         # (N,)
        dv_measured: np.ndarray, # (N,)
        cell_ids: np.ndarray,    # (N,)
        cycles: np.ndarray,      # (N,)
    ):
        self.features = torch.as_tensor(features, dtype=torch.float32)
        self.soh = torch.as_tensor(soh, dtype=torch.float32).unsqueeze(-1)
        self.dv = torch.as_tensor(dv_measured, dtype=torch.float32).unsqueeze(-1)
        self.cell_ids = torch.as_tensor(cell_ids, dtype=torch.long)
        self.cycles = torch.as_tensor(cycles, dtype=torch.float32).unsqueeze(-1)

    def __len__(self):
        return len(self.features)

    def __getitem__(self, idx):
        return (
            self.features[idx],
            self.soh[idx],
            self.dv[idx],
            self.cell_ids[idx],
            self.cycles[idx],
        )


# ============================================================
# Feature builder
# ============================================================

def build_features(raw: dict, cfg, scaler: StandardScaler | None = None) -> tuple[np.ndarray, StandardScaler]:
    """Assemble 132-d feature vector from raw data dict.

    Per-sample: [IC_curve(128), temp_norm, log10(cycle+1)_norm, dv_start, cap_meas_norm]
    """
    N = len(raw["soh"])
    ic_raw = raw["ic"]
    # Ensure correct shape
    if ic_raw.ndim == 1:
        ic_raw = ic_raw.reshape(1, -1)
    ic_raw = ic_raw[:, :cfg.data.ic_curve_pts].astype(np.float32)
    if ic_raw.shape[1] < cfg.data.ic_curve_pts:
        pad = np.zeros((N, cfg.data.ic_curve_pts - ic_raw.shape[1]), dtype=np.float32)
        ic_raw = np.concatenate([ic_raw, pad], axis=1)

    temp = raw["temp"].reshape(-1, 1).astype(np.float32)
    log_cycle = np.log10(raw["cycle"].reshape(-1, 1) + 1.0).astype(np.float32)
    dv = raw["dv_start"].reshape(-1, 1).astype(np.float32)
    cap = raw["capacity_meas"].reshape(-1, 1).astype(np.float32)

    aux = np.concatenate([temp, log_cycle, dv, cap], axis=1)
    aux_norm = np.clip(aux, -1e6, 1e6)  # clip raw extreme values before fitting scaler

    features_raw = np.concatenate([ic_raw, aux_norm.astype(np.float32)], axis=1)

    if scaler is None:
        scaler = StandardScaler().fit(features_raw)

    features = scaler.transform(features_raw).astype(np.float32)
    features = np.clip(features, -5.0, 5.0)  # aggressive clip for stability
    return features, scaler


# ============================================================
# Data loading — multi-source with fallback
# ============================================================

def _merge_datasets(datasets: list[dict]) -> dict:
    """Merge multiple raw data dicts, re-indexing cell_id offsets."""
    offset = 0
    merged = {"cell_id": [], "cycle": [], "soh": [], "temp": [],
              "ic": [], "dv_start": [], "capacity_meas": []}
    for ds in datasets:
        if ds is None or len(ds.get("soh", [])) == 0:
            continue
        n = len(ds["soh"])
        for key in merged:
            val = ds[key]
            if key == "cell_id":
                merged[key].append(np.asarray(val, dtype=np.int64) + offset)
            else:
                merged[key].append(np.asarray(val))
        offset += int(np.max(ds["cell_id"])) + 1 if n > 0 else 0
    return {k: np.concatenate(v) if v else np.array([]) for k, v in merged.items()}


def load_synthetic(cfg) -> dict:
    """Load cached synthetic dataset or generate fresh."""
    cache_path = cfg.data_cache / "lfp_synthetic.npz"
    if cache_path.exists():
        print(f"  Loading cached: {cache_path}")
        data = dict(np.load(cache_path, allow_pickle=True))
        return {k: np.asarray(v) for k, v in data.items()}
    print("  Generating synthetic data (cache miss) ...")
    from .battery_sim import LFPBatterySimulator
    sim = LFPBatterySimulator(cfg, seed=cfg.seed)
    return sim.generate_dataset(save_path=cfg.data_cache)


def load_all_data(cfg) -> dict:
    """Load all available datasets and merge them.

    Priority: real data (NASA + CALCE) first; synthetic as fallback if no real data found.
    """
    sources = []
    base = Path(__file__).resolve().parent.parent / "data"
    has_real = False

    # NASA PCoE
    nasa_path = base / "nasa_pcoe"
    if nasa_path.exists() and any(nasa_path.glob("*.mat")):
        print("[数据] NASA PCoE .mat 文件已检测到")
        from .real_data import load_nasa_pcoe
        nasa = load_nasa_pcoe(nasa_path)
        if len(nasa.get("soh", [])) > 0:
            sources.append(nasa)
            has_real = True
            print(f"  NASA samples: {len(nasa['soh'])}")
    else:
        print(f"[数据] NASA PCoE 未找到 ({nasa_path}/ — 跳过)")

    # CALCE
    calce_path = base / "calce"
    if calce_path.exists() and any(calce_path.iterdir()):
        print("[数据] CALCE 数据目录已检测到")
        from .real_data import load_calce
        calce = load_calce(calce_path)
        if len(calce.get("soh", [])) > 0:
            sources.append(calce)
            has_real = True
            print(f"  CALCE samples: {len(calce['soh'])}")

    if has_real:
        merged = _merge_datasets(sources)
        print(f"  合并后总样本: {len(merged['soh'])}")
        return merged

    # Fallback: synthetic
    print("[数据] 无可用的真实数据集，降级为合成数据")
    return load_synthetic(cfg)


# ============================================================
# Dataloader factory
# ============================================================

def create_dataloaders(cfg, raw_data: dict | None = None):
    """Build train/val/test dataloaders.

    Args:
        cfg: Config object
        raw_data: if provided, use directly; else auto-load (NASA > CALCE > synthetic)

    Returns:
        dl_train, dl_val, dl_test, scaler
    """
    if raw_data is None:
        raw_data = load_all_data(cfg)

    if len(raw_data["soh"]) == 0:
        raise RuntimeError("无有效数据! 请下载NASA/CALCE数据集 或 允许合成数据生成")

    features, scaler = build_features(raw_data, cfg)

    N = len(features)
    n_train = int(N * cfg.data.train_ratio)
    n_val = int(N * cfg.data.val_ratio)
    n_test = N - n_train - n_val

    soh = raw_data["soh"].astype(np.float32)
    dv = raw_data["dv_start"].astype(np.float32)
    cid = raw_data["cell_id"].astype(np.int64)
    cyc = raw_data["cycle"].astype(np.float32)

    ds = BatteryDataset(features, soh, dv, cid, cyc)
    ds_train, ds_val, ds_test = random_split(
        ds, [n_train, n_val, n_test],
        generator=torch.Generator().manual_seed(cfg.seed),
    )

    tcfg = cfg.training
    dl_train = DataLoader(ds_train, batch_size=tcfg.batch_size,
                          shuffle=True, num_workers=tcfg.num_workers,
                          pin_memory=True, drop_last=True)
    dl_val = DataLoader(ds_val, batch_size=tcfg.batch_size * 2,
                        shuffle=False, num_workers=tcfg.num_workers,
                        pin_memory=True)
    dl_test = DataLoader(ds_test, batch_size=tcfg.batch_size * 2,
                         shuffle=False, num_workers=tcfg.num_workers,
                         pin_memory=True)

    # Save scaler for deployment
    scaler_path = cfg.checkpoint_dir / "feature_scaler.pkl"
    cfg.checkpoint_dir.mkdir(parents=True, exist_ok=True)
    with open(scaler_path, "wb") as f:
        pickle.dump(scaler, f)

    print(f"\nTrain: {n_train}  Val: {n_val}  Test: {n_test}")
    print(f"Scaler saved → {scaler_path}")
    return dl_train, dl_val, dl_test, scaler
