/**
 * ============================================================
 * 【功能说明】
 * 定义一个矩形（Rectangle）类，是 Java 面向对象编程（OOP）的基础示例。
 * 该类封装了矩形的长度（l）和宽度（w）两个私有属性，
 * 并提供了计算周长（perimeter）和面积（area）的方法，
 * 以及一个带参数的构造方法用于初始化矩形对象的尺寸。
 * 该类被 TestRect.java 使用，演示了类的封装、构造器和方法的调用。
 * ============================================================
 * 【知识点】
 * 1. 类与对象 —— class 定义类，new 关键字创建对象实例。
 * 2. 封装 (Encapsulation) —— private 访问修饰符隐藏内部状态。
 * 3. 字段 (Field) / 成员变量 —— 定义在类中、方法外的变量。
 * 4. 构造方法 (Constructor) —— 与类同名、无返回值，用于初始化对象。
 * 5. this 关键字 —— 引用当前对象，用于区分成员变量和局部变量。
 * 6. 默认访问权限（包级私有）—— Rectangle 类没有 public 修饰符。
 * 7. 方法定义 —— 定义行为，有返回值类型和方法名。
 * 8. return 关键字 —— 将计算结果返回给调用者。
 * ============================================================
 */

// 声明包名为 chp2_oop，表示当前类属于 chp2_oop 包
package chp2_oop;

// 定义一个名为 Rectangle 的类，注意没有 public 修饰符
// 默认访问权限（包级私有，package-private）表示该类只能在同一个包内被访问
// 类名采用驼峰命名法（PascalCase），首字母大写
// 注意：此处的 Rectangle.java 文件不使用 public 关键字，因此文件名不要求与类名绝对匹配
// 但为了代码规范，文件名仍然与类名保持一致
class Rectangle {

    // 声明两个私有（private）整型成员变量（字段/属性）
    // private: 访问修饰符，表示该字段只能在当前类内部被访问
    // 这是面向对象封装性（Encapsulation）的体现——隐藏内部数据
    // int: 基本数据类型，表示 32 位有符号整数，取值范围 -2^31 ~ 2^31-1
    // l: 矩形的长度（length 的缩写）
    // w: 矩形的宽度（width 的缩写）
    // 多个同类型变量可以在一行声明，用逗号分隔
    private int l, w;

    // 空行，用于分隔字段声明区和方法定义区，提高代码的可读性

    // 定义计算矩形周长的方法，具有包级私有访问权限（默认访问级别）
    // 方法名: perimeter，遵循驼峰命名法（camelCase），首字母小写
    // 返回值类型: int，返回计算得到的周长值
    // 参数列表: () 空括号表示无参数，方法直接使用类的成员变量 l 和 w
    // 方法体: {} 中的代码实现具体的周长计算逻辑
    int perimeter() {

        // return 关键字用于将计算结果返回给方法的调用者
        // 2 * (l + w): 矩形的周长公式 C = 2 × (长 + 宽)
        // 这里的 l 和 w 是当前对象（this）的成员变量
        // 在方法内部可以直接访问当前对象的 private 字段
        // 表达式的结果是一个 int 类型的值，与方法声明的返回类型一致
        return 2 * (l + w);

    // 右花括号表示 perimeter 方法的结束
    }

    // 空行，用于分隔两个方法定义，提高代码的可读性

    // 定义计算矩形面积的方法，具有包级私有访问权限
    // 方法名: area
    // 返回值类型: int
    // 无参数，直接使用类的成员变量
    int area() {

        // return 关键字返回面积计算结果
        // l * w: 矩形的面积公式 S = 长 × 宽
        // 直接使用当前对象的 l 和 w 字段参与计算
        return l * w;

    // 右花括号表示 area 方法的结束
    }

    // 空行，用于分隔方法与构造方法，提高代码的可读性

    // 定义构造方法（Constructor），与类名 Rectangle 完全相同
    // 构造方法没有返回值类型（连 void 都不写）
    // 构造方法在创建对象时自动调用，用于初始化对象的成员变量
    // 参数: int l 和 int w，分别接收用户传入的长度和宽度值
    // 注意: 参数名 l 和 w 与成员变量名相同，产生"变量遮蔽"（Shadowing）现象
    Rectangle(int l, int w) {

        // this 关键字代表当前正在被创建的对象实例
        // this.l 引用的是成员变量（类的字段 l）
        // 右边的 l 是构造方法参数（局部变量 l）
        // 使用 this 关键字可以解决成员变量与局部变量同名时的歧义
        // 将传入的参数值赋给当前对象的成员变量
        this.l = l;

        // this.w 引用的是成员变量（类的字段 w）
        // 右边的 w 是构造方法参数
        // 将传入的宽度值赋给当前对象的 w 字段
        this.w = w;

    // 右花括号表示构造方法的结束
    }

// 右花括号表示 Rectangle 类的结束
}
