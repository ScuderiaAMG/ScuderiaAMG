%% 实验6 — D5区电阻量程测量 & 滞后校正可行性分析
%  比例环节法测量可调电阻范围, 并分析C2=1μF约束下的可行性
%
%  测量原理: 反相比例放大器 Vout = -(Rx/R_ref)×Vin

clear; clc; close all;

fprintf('╔══════════════════════════════════════════════╗\n');
fprintf('║  D5区电阻量程测量 & 滞后校正可行性分析     ║\n');
fprintf('╚══════════════════════════════════════════════╝\n\n');

% ========================================================================
%% 1. 测量原理与步骤
% ========================================================================
R_ref = 100e3;  % 参考电阻 100kΩ

fprintf('【测量原理】反相比例放大器\n');
fprintf('  |增益| = Rx / R_ref\n');
fprintf('  Rx = |Vout/Vin| × R_ref\n\n');

fprintf('【测量步骤】\n');
fprintf('  1. R_ref=100kΩ 接入运放(-)与信号源之间\n');
fprintf('  2. 待测Rx接入运放(-)与输出之间\n');
fprintf('  3. 运放(+)接地\n');
fprintf('  4. Vin=1.0V DC, 测量Vout\n');
fprintf('  5. Rx = |Vout| × 100 (kΩ)\n\n');

% ========================================================================
%% 2. 仿真验证
% ========================================================================
fprintf('【仿真参考】R_ref=100kΩ, Vin=1.0V\n\n');
fprintf('  Rx(kΩ)  │  |增益| │ Vout(V) │ 备注\n');
fprintf('  ────────┼────────┼─────────┼──────────\n');

for Rx = [10e3, 50e3, 100e3, 200e3, 500e3, 800e3, 999e3]
    gain = Rx / R_ref;
    Vout = gain * 1;
    note = '';
    if Rx > 800e3, note = '接近量程上限';
    elseif Rx > 500e3, note = '噪声敏感区';
    elseif Rx > 100e3, note = '✓ 理想范围';
    else note = '✓';
    end
    fprintf('  %7.0f │ %6.1f  │ %7.2f  │ %s\n', Rx/1e3, gain, Vout, note);
end

fprintf('\n注意: 若Vout超过运放电源电压则饱和, 需减小Vin或R_ref。\n\n');

% ========================================================================
%% 3. 滞后校正所需电阻 vs D5量程
% ========================================================================
fprintf('====== 滞后校正电阻需求 vs D5量程 ======\n\n');

C2 = 1e-6;
fprintf('C2=1μF约束下, T=R2×C2, T_max=%.4fs\n\n', 999.9e3*C2);

% 计算各PM目标所需R1,R2
fprintf('  PM目标 │ 所需C2  │ 所需R2  │ 所需R1  │ R1超量程?\n');
fprintf('  ───────┼─────────┼─────────┼─────────┼──────────\n');

for pm_tgt = [40, 45, 50]
    if pm_tgt <= 40, eps_v = 10;
    elseif pm_tgt <= 45, eps_v = 10;
    else eps_v = 11;
    end
    k_v = 5;

    wc_new = cotd(pm_tgt + eps_v) / 0.3;
    beta_v = 30 / (wc_new * sqrt(0.09*wc_new^2 + 1));
    T_v = k_v / wc_new;

    R2_need = T_v / C2;
    R1_need = R2_need * (beta_v - 1);

    exceed = '';
    if R1_need > 999.9e3, exceed = sprintf('✗ 超出%.0fkΩ', (R1_need-999.9e3)/1e3);
    elseif R2_need > 999.9e3, exceed = sprintf('✗ R2超%.0fkΩ', (R2_need-999.9e3)/1e3);
    else exceed = '✓';
    end

    fprintf('  %4.0f°  │ %5.0fkΩ │ %5.0fkΩ │ %5.0fkΩ │ %s\n', ...
            pm_tgt, T_v/C2/1e3, R2_need/1e3, R1_need/1e3, exceed);
end

fprintf('\n  结论: C2=1μF下所有PM≥40°方案均超出D5量程!\n');
fprintf('  最小需求: C2≥%.1fμF或R≥%.0fkΩ\n\n', ...
        1.4, 1.4e6/1e3);

